#Requires -Version 7.0
# UserPromptSubmit hook (CLAUDE.md §12.1): the only writer of decision evidence. A prompt is
# captured only when the whole prompt is exactly one of:
#   APPROVE PLAN <run-id> <first 12 hex of the plan's SHA-256>
#   REJECT PLAN <run-id> <first 12 hex>
#   REVISE PLAN <run-id> <first 12 hex>: <what to change>
# The decision is appended to runs/<id>/approval/decisions.jsonl under the run's state.lock.
# It takes effect only when `state.ps1 decide` applies it; decide also checks the prompt's
# origin in the session transcript, which does not exist yet while this hook runs.
#
# This hook also fires for system-generated prompts (background-agent notifications carry
# subagent text). Those are never captured: they are wrapped in markup, so they are never a
# standalone decision phrase. A prompt that mentions a decision phrase without being one is
# let through and not recorded; a prompt that starts like one but is malformed, or is not
# valid for the current plan, is blocked with the reason, and nothing is recorded.
param([string]$ProjectDir, [string]$RunsRoot, [string]$StateScript)
. (Join-Path $PSScriptRoot 'common.ps1')

function Write-Context([string]$Text) {
    [ordered]@{ hookSpecificOutput = [ordered]@{ hookEventName = 'UserPromptSubmit'; additionalContext = $Text } } | ConvertTo-Json -Compress -Depth 5
    exit 0
}
function Write-Block([string]$Reason) {
    [ordered]@{ decision = 'block'; reason = "Not recorded: $Reason" } | ConvertTo-Json -Compress
    exit 0
}

try {
    Initialize-HookContext $ProjectDir $RunsRoot $StateScript
    $in = Read-HookInput
    $prompt = "$($in['prompt'])"
    if ($prompt -cnotmatch '(APPROVE|REJECT|REVISE) PLAN') { exit 0 }
    $text = $prompt.Trim()

    if ($text.StartsWith('<') -or $prompt -match '<(task-notification|agent-message|system-reminder)\b') {
        Write-Context 'This prompt was generated by the system (for example a background-agent notification). Decision phrases inside it are never recorded as the user''s decision.'
    }
    if ($text -cnotmatch '^(APPROVE|REJECT|REVISE) PLAN\b') {
        Write-Context 'The prompt mentions a plan decision but is not one: only a prompt that consists of exactly one decision command is recorded. Nothing was recorded.'
    }

    $runPattern = '[A-Za-z0-9][A-Za-z0-9._-]*'
    $feedback = $null
    if ($text -cmatch "^(APPROVE|REJECT) PLAN ($runPattern) ([0-9a-f]{12})$") {
        $decision = if ($Matches[1] -eq 'APPROVE') { 'approve' } else { 'reject' }
        $runId = $Matches[2]; $prefix = $Matches[3]
    }
    elseif ($text -cmatch "(?s)^REVISE PLAN ($runPattern) ([0-9a-f]{12}):[ \t]*(\S.*)$") {
        $decision = 'request_changes'
        $runId = $Matches[1]; $prefix = $Matches[2]; $feedback = $Matches[3].Trim()
    }
    else {
        Write-Block 'a decision must be exactly ''APPROVE PLAN <run-id> <hash12>'', ''REJECT PLAN <run-id> <hash12>'', or ''REVISE PLAN <run-id> <hash12>: <changes>'', where <hash12> is the first 12 hex characters of the plan''s SHA-256 shown by the coordinator.'
    }
    foreach ($k in 'prompt_id', 'session_id', 'transcript_path') {
        if (-not "$($in[$k])".Trim()) { Write-Block "the hook input has no '$k', so the decision could not be tied to this session." }
    }
    $runDir = Join-Path $script:RunsRoot $runId
    if (-not (Test-Path -LiteralPath (Join-Path $runDir 'state.json') -PathType Leaf)) { Write-Block "there is no run '$runId'." }

    $lock = Enter-RunLock $runDir
    try {
        $status = Invoke-StateScript @('ledger-status', '-RunId', $runId)
        if ($status.ExitCode -ne 0 -or -not $status.Json) { Write-Block "the run's state could not be read: $($status.Stderr)" }
        $s = $status.Json
        if (-not $s.decidable) { Write-Block "the plan of run $runId cannot be decided on now ($(@($s.blockers) -join '; ')); approval status: $($s.approval_status)." }
        if (-not $s.plan_sha256 -or $s.plan_sha256 -ne $s.accepted_plan_sha256) { Write-Block 'plan.md is not the accepted plan.' }
        if (-not $s.plan_sha256.StartsWith($prefix)) { Write-Block "'$prefix' is not the current plan (version $($s.plan_version), $($s.plan_sha256.Substring(0, 12))). The plan may have changed since it was shown to you." }
        if (-not $s.ledger_valid) { Write-Block "the decision ledger is invalid; the coordinator must run 'state.ps1 quarantine-ledger' first ($(@($s.ledger_problems) -join ' '))." }
        if ($s.quarantine_in_progress) { Write-Block "a ledger quarantine is unfinished; the coordinator must run 'state.ps1 quarantine-ledger' again first." }
        if ($decision -eq 'approve' -and $s.approval_status -eq 'approved') { Write-Block 'this plan is already approved.' }

        $seq = [int]$s.line_count + 1
        $entry = [ordered]@{
            schema          = 1
            seq             = $seq
            decision_id     = 'dec-{0:000}' -f $seq
            prev_sha256     = "$($s.last_line_sha256)"
            run_id          = $runId
            decision        = $decision
            plan_sha256     = "$($s.plan_sha256)"
            plan_version    = [int]$s.plan_version
            prompt_sha256   = Get-Sha256 $prompt
            prompt_id       = "$($in['prompt_id'])"
            session_id      = "$($in['session_id'])"
            transcript_path = "$($in['transcript_path'])"
            recorded_at     = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
            source          = 'user-prompt-submit'
        }
        if ($feedback) { $entry.feedback = $feedback }
        $ledgerPath = Join-Path $runDir 'approval' 'decisions.jsonl'
        New-Item -ItemType Directory -Path (Split-Path $ledgerPath) -Force | Out-Null
        $existing = if (Test-Path -LiteralPath $ledgerPath -PathType Leaf) { [System.IO.File]::ReadAllText($ledgerPath) } else { '' }
        if ($existing -and -not $existing.EndsWith("`n")) { $existing += "`n" }
        Write-TextFileAtomic $ledgerPath ($existing + ($entry | ConvertTo-Json -Compress) + "`n")
    }
    finally { $lock.Dispose() }

    $what = switch ($decision) { 'approve' { 'approval' } 'reject' { 'rejection' } default { 'change request' } }
    Write-Context ("The user's $what of plan version $($entry.plan_version) ($prefix) in run $runId was recorded as ledger entry $($entry.decision_id). " +
        "Coordinator: apply it now with 'pwsh -NoProfile -File scripts/state.ps1 decide -RunId $runId'. decide also checks this prompt's origin in the session transcript; report its result to the user.")
}
catch {
    # Fail closed: nothing is recorded. The prompt itself is blocked so the user sees why.
    [ordered]@{ decision = 'block'; reason = "Not recorded: the decision could not be captured ($($_.Exception.Message))." } | ConvertTo-Json -Compress
    exit 0
}
